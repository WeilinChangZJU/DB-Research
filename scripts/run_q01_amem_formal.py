"""Run the frozen serial real-model Q01 A-MEM workloads in order.

The command is intentionally strict: it verifies the frozen input hashes and
official A-MEM file hashes before starting, refuses to run without a model
credential, and invokes the two workload runners one at a time with resume.
When both finish, it invokes ``review_q01_amem_formal.py`` to produce the
state/source/cost gate report.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Any

from bemula.research.manifest import sha256_tree


PINNED_AMEM_COMMIT = "f9a173dec325d84fcc97e7828775c7b241c33466"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _source_tree_files_only(root: Path) -> str:
    """Hash the external source tree with the same policy as run manifests.

    The freeze receipt is produced by the shared ``sha256_tree`` helper.  A
    second ad-hoc walker used to include a git checkout's ``.git`` internals,
    so every valid clone failed source-tree verification despite being at the
    pinned commit.  Reusing the canonical helper keeps the freeze check
    independent of VCS metadata and transient bytecode/cache files.
    """

    return sha256_tree(root)


def _git_commit(root: Path) -> str | None:
    """Return the checked-out commit when the external clone is a git tree."""

    try:
        completed = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "HEAD"],
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    value = completed.stdout.strip()
    return value or None


def _write_blocker(path: Path, *, message: str, freeze: Path) -> None:
    payload = {
        "schema_version": 1,
        "status": "blocked_missing_external_model_state",
        "message": message,
        "freeze_path": str(freeze.resolve()),
        "api_key_configured": bool(os.environ.get("OPENAI_API_KEY")),
        "model": os.environ.get("BEMULA_AGENT_MODEL", "deepseek-flash"),
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")


def _resolve_amem_path(freeze_path: Path) -> Path:
    """Resolve the frozen checkout, allowing an explicit env override.

    Freeze receipts generated by ``build_q01_amem_freeze.py`` carry the
    absolute checkout path used to hash the source.  Reusing that path by
    default prevents a valid local receipt from silently checking a different
    sibling clone; collaborators can override it with ``BEMULA_AMEM_PATH``
    after copying the same pinned checkout to another location.
    """

    configured = os.environ.get("BEMULA_AMEM_PATH")
    if configured:
        return Path(configured).expanduser().resolve()
    try:
        payload = json.loads(freeze_path.read_text(encoding="utf-8"))
        frozen_path = payload.get("official_amem", {}).get("path")
        if frozen_path:
            return Path(str(frozen_path)).expanduser().resolve()
    except (OSError, json.JSONDecodeError, AttributeError):
        pass
    return (freeze_path.parents[2] / "_amem_extract" / f"A-mem-{PINNED_AMEM_COMMIT}").resolve()


def _verify_freeze(
    freeze_path: Path,
    *,
    agent_model: str,
    embedding_backend: str,
    embedding_model: str,
    retrieve_k: int,
    locomo: Path,
    longmemeval: Path,
    amem_path: Path,
) -> dict[str, Any]:
    freeze = json.loads(freeze_path.read_text(encoding="utf-8"))
    model_config = freeze["model_config"]
    model = model_config["model"]
    if agent_model != model:
        raise RuntimeError(f"agent model {agent_model!r} differs from frozen model {model!r}")
    expected_backend = model_config.get("embedding_backend")
    if expected_backend is not None and embedding_backend != expected_backend:
        raise RuntimeError(
            f"embedding backend {embedding_backend!r} differs from frozen backend {expected_backend!r}"
        )
    expected_retrieve_k = model_config.get("retrieve_k")
    if expected_retrieve_k is not None and retrieve_k != expected_retrieve_k:
        raise RuntimeError(
            f"retrieve_k {retrieve_k!r} differs from frozen retrieve_k {expected_retrieve_k!r}"
        )
    expected_thinking = model_config.get("thinking")
    if expected_thinking is not None:
        actual_thinking = os.environ.get("BEMULA_THINKING", "disabled")
        if actual_thinking != expected_thinking:
            raise RuntimeError(
                f"BEMULA_THINKING {actual_thinking!r} differs from frozen thinking mode {expected_thinking!r}"
            )
    expected_amem_temperature = model_config.get("amem_temperature")
    if expected_amem_temperature is not None:
        actual_amem_temperature = float(os.environ.get("BEMULA_AMEM_TEMPERATURE", "0.0"))
        if actual_amem_temperature != float(expected_amem_temperature):
            raise RuntimeError(
                "BEMULA_AMEM_TEMPERATURE "
                f"{actual_amem_temperature!r} differs from frozen A-MEM temperature "
                f"{float(expected_amem_temperature)!r}"
            )
    expected_replay_policy = model_config.get("provider_replay_policy")
    if expected_replay_policy is not None:
        actual_replay_policy = os.environ.get(
            "BEMULA_PROVIDER_REPLAY_POLICY", "m0_repeat_request_key_cassette"
        )
        if actual_replay_policy != expected_replay_policy:
            raise RuntimeError(
                f"provider replay policy {actual_replay_policy!r} differs from frozen policy "
                f"{expected_replay_policy!r}"
            )
    # New freeze receipts include ``random_seed`` even when it is explicitly
    # null.  Enforce that null as well as an integer so an ambient process
    # seed cannot silently change a supposedly frozen run.  Older receipts
    # without the key retain their legacy optional behavior.
    if "random_seed" in model_config:
        expected_seed = model_config.get("random_seed")
        raw_seed = os.environ.get("BEMULA_RANDOM_SEED")
        try:
            actual_seed = int(raw_seed) if raw_seed not in (None, "") else None
        except (TypeError, ValueError) as exc:
            raise RuntimeError(
                f"BEMULA_RANDOM_SEED {raw_seed!r} is not an integer"
            ) from exc
        if actual_seed != expected_seed:
            raise RuntimeError(
                f"BEMULA_RANDOM_SEED {raw_seed!r} differs from frozen random seed {expected_seed!r}"
            )
    expected_base_url = model_config.get("base_url")
    if expected_base_url is not None:
        actual_base_url = os.environ.get("OPENAI_BASE_URL")
        if actual_base_url != expected_base_url:
            raise RuntimeError(
                f"OPENAI_BASE_URL {actual_base_url!r} differs from frozen base_url {expected_base_url!r}"
            )
    if embedding_backend == "local":
        local = model_config.get("local_embedding_variant", {})
        if embedding_model != local.get("model"):
            raise RuntimeError(
                f"local embedding model {embedding_model!r} differs from frozen local variant {local.get('model')!r}"
            )
    elif embedding_backend == "api":
        if embedding_model != model_config.get("embedding_model"):
            raise RuntimeError(
                f"API embedding model {embedding_model!r} differs from frozen model {model_config.get('embedding_model')!r}"
            )
    else:
        raise RuntimeError(f"unsupported embedding backend: {embedding_backend!r}")
    for key, path in (("locomo", locomo), ("longmemeval_s", longmemeval)):
        expected = freeze["inputs"][key]["sha256"]
        actual = _sha256(path)
        if actual != expected:
            raise RuntimeError(f"{key} input hash mismatch: expected {expected}, got {actual}")
    official = freeze["official_amem"]
    expected_commit = official.get("commit") or official.get("git_commit") or PINNED_AMEM_COMMIT
    if expected_commit:
        actual_commit = _git_commit(amem_path)
        if actual_commit is None:
            raise RuntimeError(
                "official A-MEM path is not a git checkout; cannot verify the frozen commit"
            )
        if actual_commit != expected_commit:
            raise RuntimeError(
                f"official A-MEM commit mismatch: expected {expected_commit}, got {actual_commit}"
            )
    robust = amem_path / "memory_layer_robust.py"
    requirements = amem_path / "requirements.txt"
    if _sha256(robust) != official["memory_layer_robust_sha256"]:
        raise RuntimeError("official A-MEM memory_layer_robust.py hash mismatch")
    if _sha256(requirements) != official["requirements_sha256"]:
        raise RuntimeError("official A-MEM requirements.txt hash mismatch")
    if _source_tree_files_only(amem_path) != official["source_tree_sha256_files_only"]:
        raise RuntimeError("official A-MEM source tree hash mismatch")
    return freeze


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--freeze", type=Path, default=Path("experiment_results_20261114/q01_amem_freeze/freeze.json"))
    parser.add_argument("--locomo", type=Path, default=Path("experiment_results_20261114/q01_inputs/locomo_explicit_histories.jsonl"))
    parser.add_argument("--longmemeval", type=Path, default=Path("experiment_results_20261114/q01_inputs/longmemeval_s_explicit_histories.jsonl"))
    parser.add_argument("--out-root", type=Path, default=Path("experiment_results_20261114/q01_runs/formal_real"))
    parser.add_argument("--review-out", type=Path, default=Path("experiment_results_20261114/q01_amem_freeze/formal_real_review.json"))
    parser.add_argument("--agent-model", default=os.environ.get("BEMULA_AGENT_MODEL", "deepseek-flash"))
    parser.add_argument("--embedding-backend", default=os.environ.get("BEMULA_EMBED_BACKEND", "api"))
    parser.add_argument(
        "--embedding-model",
        default=os.environ.get("BEMULA_HF_EMBED_MODEL", os.environ.get("BEMULA_EMBED_MODEL", "text-embedding-3-small")),
    )
    parser.add_argument("--retrieve-k", type=int, default=10)
    parser.add_argument(
        "--m3-mode",
        choices=("materialized", "recheck", "conservative_full"),
        default="conservative_full",
        help="M3 dependency policy; conservative_full is the correctness baseline.",
    )
    parser.add_argument("--query-limit", type=int, default=1)
    parser.add_argument("--locomo-limit", type=int, default=None)
    parser.add_argument("--longmemeval-limit", type=int, default=None)
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--evidence-level", default="real_model_formal")
    args = parser.parse_args()
    if args.query_limit < 1:
        raise SystemExit("--query-limit must be >= 1")
    freeze_path = args.freeze.resolve()
    amem_path = _resolve_amem_path(freeze_path)
    blocker_path = args.out_root / "formal_run_blocker.json"
    try:
        freeze = _verify_freeze(
            freeze_path,
            agent_model=args.agent_model,
            embedding_backend=args.embedding_backend,
            embedding_model=args.embedding_model,
            retrieve_k=args.retrieve_k,
            locomo=args.locomo.resolve(),
            longmemeval=args.longmemeval.resolve(),
            amem_path=amem_path,
        )
    except Exception as exc:
        _write_blocker(blocker_path, message=f"freeze verification failed: {type(exc).__name__}: {exc}", freeze=freeze_path)
        print(blocker_path)
        return 2
    if not os.environ.get("OPENAI_API_KEY"):
        _write_blocker(blocker_path, message="OPENAI_API_KEY is not configured; no real-model call was started", freeze=freeze_path)
        print(blocker_path)
        return 2

    args.out_root.mkdir(parents=True, exist_ok=True)
    child_env = dict(os.environ)
    child_env["BEMULA_SOURCE_ROOT"] = str(Path(__file__).resolve().parents[1])
    # Pass the exact checkout that was hash/commit-verified above.  Without
    # this explicit propagation, AmemAdapter would fall back to a sibling
    # directory and the child runner could execute a different source tree
    # than the one used for freeze validation.
    child_env["BEMULA_AMEM_PATH"] = str(amem_path)
    if freeze["model_config"].get("amem_temperature") is not None:
        child_env["BEMULA_AMEM_TEMPERATURE"] = str(
            freeze["model_config"]["amem_temperature"]
        )
    if freeze["model_config"].get("provider_replay_policy") is not None:
        child_env["BEMULA_PROVIDER_REPLAY_POLICY"] = str(
            freeze["model_config"]["provider_replay_policy"]
        )
    official = freeze["official_amem"]
    child_env["BEMULA_FREEZE_SHA256"] = _sha256(freeze_path)
    child_env["BEMULA_AMEM_COMMIT"] = str(
        official.get("commit") or official.get("git_commit") or PINNED_AMEM_COMMIT
    )
    child_env["BEMULA_AMEM_SOURCE_TREE_SHA256"] = str(
        official.get("source_tree_sha256_files_only", "unknown")
    )
    child_env["BEMULA_MODEL_CONFIG_SHA256"] = hashlib.sha256(
        json.dumps(freeze.get("model_config", {}), sort_keys=True).encode("utf-8")
    ).hexdigest()
    child_env["BEMULA_EMBED_BACKEND"] = args.embedding_backend
    if args.embedding_backend == "local":
        child_env["BEMULA_HF_EMBED_MODEL"] = args.embedding_model
    else:
        child_env["BEMULA_EMBED_MODEL"] = args.embedding_model
    runner = Path(__file__).with_name("run_q01_amem_paired.py")
    workloads = (
        ("locomo", args.locomo.resolve(), args.locomo_limit),
        ("longmemeval_s", args.longmemeval.resolve(), args.longmemeval_limit),
    )
    for name, input_path, limit in workloads:
        out = args.out_root / name
        command = [
            sys.executable,
            str(runner),
            "--histories", str(input_path),
            "--out", str(out),
            "--retrieve-k", str(args.retrieve_k),
            "--m3-mode", args.m3_mode,
            "--query-limit", str(args.query_limit),
            "--agent-model", args.agent_model,
        ]
        if limit is not None:
            command.extend(["--limit", str(limit)])
        if args.resume:
            command.append("--resume")
        subprocess.run(command, check=True, env=child_env)

    reviewer = Path(__file__).with_name("review_q01_amem_formal.py")
    subprocess.run(
        [
            sys.executable,
            str(reviewer),
            "--locomo-run", str(args.out_root / "locomo"),
            "--longmemeval-run", str(args.out_root / "longmemeval_s"),
            "--locomo-expected", str(args.locomo_limit if args.locomo_limit is not None else 10),
            "--longmemeval-expected", str(args.longmemeval_limit if args.longmemeval_limit is not None else 500),
            "--out", str(args.review_out),
            "--evidence-level", args.evidence_level,
        ],
        check=True,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
